                                    <p class="gender">Con el florecimiento del deporte de masas, fundamentalmente fútbol, entre la década de los veinte y treinta del siglo XX, sin olvidar otras disciplinas como el boxeo, la lucha canaria o las carreras de galgos, en la ciudad de Las Palmas de Gran Canaria se hizo imprescindible una instalación que albergara grandes espectáculos y tuviese la capacidad de reunir afluencias masivas de espectadores.<br><br>Esa función le correspondió en esta época, principalmente y por encima de otras localizaciones, al recordado Campo España, ubicado en las conocidas Fincas Unidas del barrio de Arenales. Así lo constatan todas las referencias históricas de entonces. Su época de esplendor antecedió a la inauguración del Estadio Insular (1944), concebido precisamente como el coliseo moderno que demandaba el aumento demográfico y el auge del interés por las distintas competiciones. El Campo España mantuvo cierta vigencia hasta finales de los sesenta, si bien fue rápidamente desplazado por un Insular que le doblaba, con aforo para 20.000 personas, y presentaba mayores comodidades. El Insular acogió, por más de medio siglo, hasta comienzos del XXI, todos los grandes eventos celebrados en la capital, tanto de índole deportivo como cultural o social. Toda la vida de la UD Las Palmas desde su fundación, en 1949, hasta la definitiva mudanza en 2003 a Siete Palmas, se desarrolló en un punto neurálgico hoy convertido en parque urbano pero que permanece como patrimonio afectivo de toda una isla por su carácter pionero y un legado inigualable.</p>
