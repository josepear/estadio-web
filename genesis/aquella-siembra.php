                            <p class="gender">El 12 de septiembre de 2002, ya con la fecha de inauguración oficial fijada para mayo de 2003, y con las obras enfilando su tramo final, se procedió a la siembra del césped sobre la superficie del terreno de juego. Un acto simbólico de enorme valor porque evidenciaba el correcto desarrollo de las obras y el cumplimiento de los plazos.<br><br>Desde el Cabildo de Gran Canaria se organizó un acto sencillo, con masiva presencia de medios de comunicación, y en el que la presidenta María Eugenia Márquez, acompañada por el consejero de Deportes, Gonzalo Angulo, quiso tener un recuerdo con la figura de Pedro Lezcano, histórico dirigente político que propulsó, en sus inicios, este proyecto.<br><br>Por parte de la UD Las Palmas, destinada a ser la inquilina del recinto, su máximo dirigente, Luis González, encabezó la representación de la entidad.<br><br>Los técnicos de entonces rechazaron la instalación de tepes de hierba artificial o importada, como ya era uso común en otros estadios, dado que no había premura de tiempo y se estipulaba que en unos tres meses ya agarraría el césped y estaría en perfecto estado de revista para su posterior utilización. Unas capas de grava especial añadidas al subsuelo, la instalación impermeabilizante así como la colocación de los tubos de drenaje y de aspersores de riego constituyeron las etapas previas en los trabajos de adecuación del firme que se iniciaron tres meses antes.
